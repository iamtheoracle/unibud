import test from "node:test";
import assert from "node:assert/strict";
import { readFileSync } from "node:fs";

const route=readFileSync(new URL("../src/app/api/internal/operations/mfa/notifications/route.ts",import.meta.url),"utf8");
const component=readFileSync(new URL("../src/app/operations/security/mfa/operations-mfa-notifications.tsx",import.meta.url),"utf8");
const page=readFileSync(new URL("../src/app/operations/security/mfa/page.tsx",import.meta.url),"utf8");
const migration=readFileSync(new URL("../../../database/migrations/0039_operations_mfa_security_notifications.sql",import.meta.url),"utf8");
const e2e=readFileSync(new URL("../../../scripts/e2e/operations-mfa.mjs",import.meta.url),"utf8");
const fixture=readFileSync(new URL("../src/app/e2e/operations-mfa/page.tsx",import.meta.url),"utf8");

test("MFA notification API is bound to a validated same-origin account session",()=>{
 assert.match(route,/hasSameOrigin\(request\)/);
 assert.match(route,/readSessionCookie\(request\)/);
 assert.match(route,/sessions\.validate\(token\)/);
 assert.match(route,/createSignedSessionContextFromEnvironment\(/);
 assert.match(route,/withSignedSessionTransaction\(/);
 assert.match(route,/unibud_operator_mfa_list_notifications/);
 assert.match(route,/unibud_operator_mfa_mark_notification_read/);
 assert.match(route,/notification_read/);
 assert.match(route,/Cache-Control.*no-store/);
 assert.doesNotMatch(route,/body\.(accountId|sessionId|role|permissions)/);
});

test("security inbox is rendered on the authenticator security page and supports read state",()=>{
 assert.match(page,/OperationsMfaNotifications/);
 assert.match(component,/Security notifications/);
 assert.match(component,/Mark as read/);
 assert.match(component,/credentials:"same-origin"/);
 assert.match(component,/cache:"no-store"/);
 assert.match(component,/external email or SMS delivery is not represented/);
});

test("notification persistence is generated by the immutable MFA audit stream and scoped by account",()=>{
 assert.match(migration,/AFTER INSERT ON public\.unibud_operator_mfa_events/);
 assert.match(migration,/UNIQUE\(account_id,event_id\)/);
 assert.match(migration,/ENABLE ROW LEVEL SECURITY/);
 assert.match(migration,/FORCE ROW LEVEL SECURITY/);
 assert.match(migration,/account_id=unibud_private\.current_account_id\(\)/);
 assert.match(migration,/current_session_id\(\)/);
 assert.match(migration,/REVOKE ALL ON public\.unibud_operator_mfa_notifications/);
 assert.match(migration,/notification_read/);
 assert.doesNotMatch(migration,/sendgrid|twilio|smtp|fetch\(/i);
});

test("isolated browser workflow covers the security inbox without a live notification provider",()=>{
 assert.match(fixture,/OperationsMfaNotifications/);
 assert.match(e2e,/path\.endsWith\("\/notifications"\)&&method==="GET"/);
 assert.match(e2e,/Security notifications/);
 assert.match(e2e,/An Operations security change was approved/);
 assert.match(e2e,/Mark as read/);
 assert.match(e2e,/noticeBody\.notificationId/);
});
